function editDistance(a, b) {
  if (!a) return b.length;
  if (!b) return a.length;
  const row = Array.from({length:b.length+1}, (_,i)=>i);
  for(let i=1;i<=a.length;i++) {
    let last = row[0];row[0]=i;
    for(let j=1;j<=b.length;j++) {
      const previous=row[j];
      row[j]=Math.min(row[j]+1,row[j-1]+1,last+(a[i-1]===b[j-1]?0:1));
      last=previous;
    }
  }
  return row[b.length];
}
function scoreTeam(query, name) {
  const q=normalize(query),n=normalize(name);
  if (!q) return -1;
  if(q===n) return 1000;
  if(n.startsWith(q)) return 700-Math.min(n.length-q.length,100);
  if(n.includes(q)) return 550-Math.min(n.indexOf(q),100);
  const words=String(name).toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
  if(words.some(w=>w.startsWith(q)))return 460;
  // Ordered characters allow incomplete searches, e.g. "astrcr" for AstroCare.
  let k=0;
  for(const char of n)if(char===q[k])k++;
  if(k===q.length && q.length>=3)return 260-Math.max(0,n.length-q.length);
  // Simple edit distance for misspelled names, with shorter queries handled more strictly.
  const max=Math.min(3,Math.floor(q.length/3));
  if(max>0){
    const dist=editDistance(q,n);
    if(dist<=max)return 350-dist*45;
    for(const word of words){const d=editDistance(q,word);if(d<=max)return 300-d*45;}
  }
  return -1;
}
function matchingTeams(query) {
  return teams.map((team,index)=>({...team,index,score:scoreTeam(query,team.name)}))
    .filter(team=>team.score>=0)
    .sort((a,b)=>b.score-a.score||a.name.localeCompare(b.name)||a.index-b.index)
    .slice(0,8);
}
function maskEmail(email) {
  const parts=email.split('@');
  if(parts.length!==2)return email;
  const local=parts[0];
  return local.slice(0,Math.min(3,local.length))+'•••@'+parts[1];
}
